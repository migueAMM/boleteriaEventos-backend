-- Ejecutar SELECT individualmente en SQL Developer (F9).
-- Para PDF desde Java: ejecutar las consultas en repositorios y generar PDF en servicio.
-- Los reportes 5/7/8 consideran ventas confirmadas ACTIVA/USADA.


-- =========================================================
-- REPORTE 1: PROXIMAS FUNCIONES TURISTICAS
-- =========================================================

SELECT
    F.ID_FUNCION,
    A.NOMBRE AS ATRACCION,
    P.NOMBRE AS PRESTADOR,
    M.NOMBRE AS MUNICIPIO,
    TO_CHAR(F.FECHA, 'DD/MM/YYYY') AS FECHA,
    F.HORA_APERTURA,
    F.HORA_CIERRE,
    F.ESTADO
FROM FUNCIONES F
JOIN ATRACCIONES A
    ON F.ID_ATRACCION = A.ID_ATRACCION
JOIN PRESTADORES P
    ON A.ID_PRESTADOR = P.ID_PRESTADOR
JOIN MUNICIPIOS M
    ON P.ID_MUNICIPIO = M.ID_MUNICIPIO
WHERE F.ESTADO = 'PROGRAMADA'
  AND F.FECHA >= TRUNC(CURRENT_DATE)
ORDER BY F.FECHA, F.HORA_APERTURA;



-- =========================================================
-- REPORTE 2: RESERVAS POR CLIENTE
-- =========================================================

SELECT
    P.ID_PERFIL,
    P.DOCUMENTO,
    P.NOMBRE AS CLIENTE,
    R.ID_RESERVA,
    R.FECHA_HORA,
    R.ESTADO,
    NVL(PL.NOMBRE, 'SIN PLAN') AS PLAN_TURISTICO
FROM PERFILES_CLIENTE P
JOIN RESERVAS R
    ON P.ID_PERFIL = R.ID_PERFIL
LEFT JOIN PLANES PL
    ON R.ID_PLAN = PL.ID_PLAN
ORDER BY P.NOMBRE, R.FECHA_HORA DESC;



-- =========================================================
-- REPORTE 3: COMPROBANTE DE RESERVA (CONFIRMADA O PENDIENTE)
-- Se utiliza BOLETAS para ambos estados: el backend no maneja RESERVA_DETALLE.
-- Pendientes muestran un resumen; las anuladas no aparecen como venta.
-- =========================================================
SELECT
    R.ID_RESERVA, P.NOMBRE AS CLIENTE, P.DOCUMENTO,
    R.FECHA_HORA, R.ESTADO AS ESTADO_RESERVA,
    B.CODIGO AS CODIGO_BOLETA, A.NOMBRE AS ATRACCION,
    F.FECHA AS FECHA_FUNCION, Z.NOMBRE AS ZONA,
    T.NOMBRE AS TIPO_ENTRADA, NVL(C.NOMBRE,'INDIVIDUAL') AS COMBO,
    B.PRECIO_PAGADO,
    CASE WHEN R.ESTADO = 'CONFIRMADA' THEN 'COMPROBANTE_COMPRA'
         ELSE 'RESUMEN_PENDIENTE' END AS TIPO_DOCUMENTO,
    SUM(B.PRECIO_PAGADO) OVER (PARTITION BY R.ID_RESERVA) AS TOTAL_RESERVA
FROM RESERVAS R
JOIN PERFILES_CLIENTE P ON P.ID_PERFIL = R.ID_PERFIL
JOIN BOLETAS B ON B.ID_RESERVA = R.ID_RESERVA
JOIN ZONAS Z ON Z.ID_ZONA = B.ID_ZONA
JOIN FUNCIONES F ON F.ID_FUNCION = Z.ID_FUNCION
JOIN ATRACCIONES A ON A.ID_ATRACCION = F.ID_ATRACCION
LEFT JOIN TIPOS_ENTRADA T ON T.ID_TIPO_ENTRADA = B.ID_TIPO_ENTRADA
LEFT JOIN COMBOS C ON C.ID_COMBO = B.ID_COMBO
WHERE R.ESTADO IN ('CONFIRMADA','PENDIENTE')
  AND B.ESTADO IN ('ACTIVA','USADA')
ORDER BY R.ID_RESERVA, B.CODIGO;


-- =========================================================
-- REPORTE 4: OCUPACION POR ZONA
-- =========================================================

SELECT
    A.NOMBRE AS ATRACCION,
    F.ID_FUNCION,
    F.FECHA,
    Z.ID_ZONA,
    Z.NOMBRE AS ZONA,
    Z.AFORO,
    COUNT(
        CASE
            WHEN B.ESTADO IN ('ACTIVA', 'USADA')
            THEN B.ID_BOLETA
        END
    ) AS CUPOS_OCUPADOS,
    Z.AFORO - COUNT(
        CASE
            WHEN B.ESTADO IN ('ACTIVA', 'USADA')
            THEN B.ID_BOLETA
        END
    ) AS CUPOS_DISPONIBLES,
    ROUND(
        COUNT(
            CASE
                WHEN B.ESTADO IN ('ACTIVA', 'USADA')
                THEN B.ID_BOLETA
            END
        ) * 100 / Z.AFORO,
        2
    ) AS PORCENTAJE_OCUPACION
FROM ZONAS Z
JOIN FUNCIONES F
    ON Z.ID_FUNCION = F.ID_FUNCION
JOIN ATRACCIONES A
    ON F.ID_ATRACCION = A.ID_ATRACCION
LEFT JOIN BOLETAS B
    ON Z.ID_ZONA = B.ID_ZONA
GROUP BY
    A.NOMBRE,
    F.ID_FUNCION,
    F.FECHA,
    Z.ID_ZONA,
    Z.NOMBRE,
    Z.AFORO
ORDER BY F.FECHA, A.NOMBRE, Z.NOMBRE;



-- =========================================================
-- REPORTE 5: INGRESOS POR ATRACCION Y TIPO DE ENTRADA
-- =========================================================

SELECT
    A.NOMBRE AS ATRACCION,
    T.NOMBRE AS TIPO_ENTRADA,
    COUNT(B.ID_BOLETA) AS BOLETAS_VENDIDAS,
    SUM(B.PRECIO_PAGADO) AS TOTAL_INGRESOS,
    ROUND(AVG(B.PRECIO_PAGADO), 2) AS PRECIO_PROMEDIO
FROM BOLETAS B
JOIN ZONAS Z
    ON B.ID_ZONA = Z.ID_ZONA
JOIN FUNCIONES F
    ON Z.ID_FUNCION = F.ID_FUNCION
JOIN ATRACCIONES A
    ON F.ID_ATRACCION = A.ID_ATRACCION
JOIN TIPOS_ENTRADA T
    ON B.ID_TIPO_ENTRADA = T.ID_TIPO_ENTRADA
JOIN RESERVAS R
    ON B.ID_RESERVA = R.ID_RESERVA
WHERE B.ESTADO IN ('ACTIVA', 'USADA')
  AND R.ESTADO = 'CONFIRMADA'
GROUP BY A.NOMBRE, T.NOMBRE
ORDER BY TOTAL_INGRESOS DESC;



-- =========================================================
-- REPORTE 6: RESERVAS POR MES Y ESTADO
-- =========================================================

SELECT
    TO_CHAR(R.FECHA_HORA, 'YYYY-MM') AS MES,
    R.ESTADO,
    COUNT(*) AS TOTAL_RESERVAS
FROM RESERVAS R
GROUP BY
    TO_CHAR(R.FECHA_HORA, 'YYYY-MM'),
    R.ESTADO
ORDER BY MES, R.ESTADO;



-- =========================================================
-- REPORTE 7: INGRESOS POR MUNICIPIO Y TIPO DE PRESTADOR
-- =========================================================

SELECT
    M.NOMBRE AS MUNICIPIO,
    TP.NOMBRE AS TIPO_PRESTADOR,
    COUNT(B.ID_BOLETA) AS BOLETAS_VENDIDAS,
    SUM(B.PRECIO_PAGADO) AS TOTAL_INGRESOS
FROM BOLETAS B
JOIN ZONAS Z
    ON B.ID_ZONA = Z.ID_ZONA
JOIN FUNCIONES F
    ON Z.ID_FUNCION = F.ID_FUNCION
JOIN ATRACCIONES A
    ON F.ID_ATRACCION = A.ID_ATRACCION
JOIN PRESTADORES P
    ON A.ID_PRESTADOR = P.ID_PRESTADOR
JOIN MUNICIPIOS M
    ON P.ID_MUNICIPIO = M.ID_MUNICIPIO
JOIN TIPOS_PRESTADOR TP
    ON P.ID_TIPO_PRESTADOR = TP.ID_TIPO_PRESTADOR
JOIN RESERVAS R
    ON B.ID_RESERVA = R.ID_RESERVA
WHERE B.ESTADO IN ('ACTIVA', 'USADA')
  AND R.ESTADO = 'CONFIRMADA'
GROUP BY M.NOMBRE, TP.NOMBRE
ORDER BY TOTAL_INGRESOS DESC;



-- =========================================================
-- REPORTE 8: COMBOS MAS VENDIDOS
-- =========================================================

SELECT
    C.ID_COMBO,
    C.NOMBRE AS COMBO,
    C.PRECIO,
    C.ESTADO,
    COUNT(DISTINCT B.ID_RESERVA) AS RESERVAS_CON_COMBO,
    COUNT(B.ID_BOLETA) AS BOLETAS_DE_COMBO,
    NVL(SUM(B.PRECIO_PAGADO), 0) AS TOTAL_INGRESOS
FROM COMBOS C
LEFT JOIN BOLETAS B
    ON C.ID_COMBO = B.ID_COMBO
   AND B.ESTADO IN ('ACTIVA', 'USADA')
   AND EXISTS (
       SELECT 1
       FROM RESERVAS R
       WHERE R.ID_RESERVA = B.ID_RESERVA
         AND R.ESTADO = 'CONFIRMADA'
   )
GROUP BY
    C.ID_COMBO,
    C.NOMBRE,
    C.PRECIO,
    C.ESTADO
ORDER BY
    RESERVAS_CON_COMBO DESC,
    TOTAL_INGRESOS DESC;



-- =========================================================
-- REPORTE 9: CLIENTES RECURRENTES
-- =========================================================

SELECT
    P.ID_PERFIL,
    P.DOCUMENTO,
    P.NOMBRE AS CLIENTE,
    U.CORREO,
    COUNT(R.ID_RESERVA) AS RESERVAS_CONFIRMADAS,
    MIN(R.FECHA_HORA) AS PRIMERA_RESERVA,
    MAX(R.FECHA_HORA) AS ULTIMA_RESERVA
FROM PERFILES_CLIENTE P
LEFT JOIN USUARIOS_SISTEMA U
    ON P.ID_USUARIO = U.ID_USUARIO
JOIN RESERVAS R
    ON P.ID_PERFIL = R.ID_PERFIL
WHERE R.ESTADO = 'CONFIRMADA'
GROUP BY
    P.ID_PERFIL,
    P.DOCUMENTO,
    P.NOMBRE,
    U.CORREO
HAVING COUNT(R.ID_RESERVA) >= 2
ORDER BY RESERVAS_CONFIRMADAS DESC, P.NOMBRE;



-- =========================================================
-- REPORTE 10: AUDITORIA DE MENORES SIN ADULTO
-- =========================================================

SELECT
    R.ID_RESERVA,
    P.NOMBRE AS CLIENTE,
    A.NOMBRE AS ATRACCION,
    F.ID_FUNCION,
    F.FECHA,
    COUNT(B.ID_BOLETA) AS BOLETAS_MENORES
FROM RESERVAS R
JOIN PERFILES_CLIENTE P
    ON R.ID_PERFIL = P.ID_PERFIL
JOIN BOLETAS B
    ON R.ID_RESERVA = B.ID_RESERVA
JOIN TIPOS_ENTRADA T
    ON B.ID_TIPO_ENTRADA = T.ID_TIPO_ENTRADA
JOIN ZONAS Z
    ON B.ID_ZONA = Z.ID_ZONA
JOIN FUNCIONES F
    ON Z.ID_FUNCION = F.ID_FUNCION
JOIN ATRACCIONES A
    ON F.ID_ATRACCION = A.ID_ATRACCION
WHERE T.REQUIERE_ADULTO = 1
  AND B.ESTADO IN ('ACTIVA', 'USADA')
  AND NOT EXISTS (
      SELECT 1
      FROM BOLETAS BA
      JOIN TIPOS_ENTRADA TA
          ON BA.ID_TIPO_ENTRADA = TA.ID_TIPO_ENTRADA
      JOIN ZONAS ZA
          ON BA.ID_ZONA = ZA.ID_ZONA
      WHERE BA.ID_RESERVA = R.ID_RESERVA
        AND ZA.ID_FUNCION = F.ID_FUNCION
        AND (TA.ES_ADULTO = 1 OR UPPER(TRIM(TA.NOMBRE)) = 'ADULTO')
        AND BA.ESTADO IN ('ACTIVA', 'USADA')
  )
GROUP BY
    R.ID_RESERVA,
    P.NOMBRE,
    A.NOMBRE,
    F.ID_FUNCION,
    F.FECHA
ORDER BY F.FECHA, R.ID_RESERVA;


